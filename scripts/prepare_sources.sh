#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# prepare_sources.sh : turn the FABulous-generated fabric into source sets for
#                      (a) Vivado / Versal emulation   build/src/fpga.f
#                      (b) iverilog simulation         build/src/sim.f
#
# Differences to the raw FABulous output:
#   * duplicated primitive files are de-duplicated (first copy wins)
#   * gf180mcuD_latchmap.v (ASIC tech-map) is dropped
#   * BlockRAM_1KB.v: the (* blackbox *) stub of the sky130 OpenRAM macro is cut
#     out and replaced by rtl/fpga/sram_1rw1r_32_256_8_sky130_fpga.v
#   * sim only: models_pack.v routing muxes get a 0.2 ns delay so transient
#     combinational rings during reconfiguration do not hang the event simulator
# The ASIC flow keeps using fabric/ untouched.
# -----------------------------------------------------------------------------
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
FAB="$HERE/fabric"
OUT="$HERE/build/src"
rm -rf "$OUT"; mkdir -p "$OUT/fabric" "$OUT/sim"

declare -A seen
while read -r f; do
    b=$(basename "$f")
    case "$b" in *latchmap*) continue ;; esac
    [[ -n "${seen[$b]+x}" ]] && continue
    seen[$b]=1
    cp "$f" "$OUT/fabric/$b"
done < <(find "$FAB/Fabric" "$FAB/Tile" -name '*.v' -type f | sort)

# strip the blackbox SRAM stub (from the "(* blackbox *)" line to its endmodule)
python3 - "$OUT/fabric/BlockRAM_1KB.v" <<'EOF'
import re, sys
p = sys.argv[1]; s = open(p).read()
n = re.subn(r"\(\* blackbox \*\)\s*module sram_1rw1r_32_256_8_sky130.*?endmodule\s*", "", s, flags=re.S)
if n[1] != 1:
    sys.exit("prepare_sources: SRAM blackbox stub not found exactly once in BlockRAM_1KB.v")
open(p, "w").write(n[0])
EOF
cp "$HERE/rtl/fpga/sram_1rw1r_32_256_8_sky130_fpga.v" "$OUT/fabric/"

# FPGA build only: Vivado 2025.2.1 functionally mis-synthesizes the fabric's MULADD
# (silicon-confirmed with blk_macprobe: result is a corrupted function of the true
# product - carry corruption in columns 1,2,6,8,10,12 of the product adder, plus an
# operand-dependent output bit 5; identical at 10/25/50 MHz; bitstream correct in RTL
# sim). use_dsp maps the MAC into a DSP58; keep_hierarchy stops the cross-boundary
# LUT merging with the config muxes that plausibly caused it. ASIC flow untouched.
sed -i 's/^module MULADD /(* use_dsp = "yes", keep_hierarchy = "yes" *)\nmodule MULADD /' "$OUT/fabric/MULADD.v"
grep -q 'use_dsp' "$OUT/fabric/MULADD.v" || { echo "MULADD use_dsp patch failed"; exit 1; }

# simulation copy of the mux models with a small delay
{
    echo '`timescale 1ns / 1ps'
    echo '// SIM-ONLY: generated by scripts/prepare_sources.sh - routing muxes with 0.2 ns delay'
    sed -e 's/assign X = S1 ? B1 : B0;/assign #0.2 X = S1 ? B1 : B0;/' \
        -e 's/assign X = S ? A1 : A0;/assign #0.2 X = S ? A1 : A0;/' "$OUT/fabric/models_pack.v"
} > "$OUT/sim/models_pack_sim.v"
[[ $(grep -c '#0.2' "$OUT/sim/models_pack_sim.v") -eq 2 ]] || { echo "mux delay patch failed"; exit 1; }

ls "$OUT"/fabric/*.v > "$OUT/fpga.f"
{ echo "$OUT/sim/models_pack_sim.v"; grep -v '/models_pack.v$' "$OUT/fpga.f"; } > "$OUT/sim.f"
echo "fabric sources: $(wc -l < "$OUT/fpga.f") files -> $OUT/fpga.f, $OUT/sim.f"
