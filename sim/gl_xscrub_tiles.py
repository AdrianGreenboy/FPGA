#!/usr/bin/env python3
"""Tile-internal X-scrub for gate-level simulation of the hardened fabric.

FABulous' gen_gl_xinit.py deposits 0 on still-X *inter-tile* nets and clears
X flops. That is not enough here: unused switch-matrix paths form
combinational loops *inside* a tile, and gate-level cells (OpenROAD/abc
resynthesise the X-optimistic RTL muxes into X-pessimistic gates) keep an X
circulating in such a loop forever. A LUT whose unused input is wired to such
a loop then outputs X even though its function does not depend on it, the
flop it feeds re-captures X and a counter never leaves X - while the RTL
(X-optimistic) simulation and the silicon both work.

This script emits ``force_block_tiles.vh``: at ``trigger`` (configuration
complete) it deposits 0 on every tile-internal wire bit that is still X.
X-only, exactly like FABulous' block: a net the configuration drives to a
defined value is never touched, so a wrongly configured fabric still
mismatches the golden reference. Real silicon powers these nets up as 0 or 1
too; a correct user design never depends on them (it resets its own state).

Usage:
  gl_xscrub_tiles.py --efpga eFPGA.nl.v --tile-dir fabric/Tile \
      --top-inst dut.eFPGA_inst --trigger config_done --out force_block_tiles.vh
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

WIRE_RE = re.compile(r"^\s*wire\s+(\[\s*(\d+)\s*:\s*(\d+)\s*\]\s*)?(\\\S+|[A-Za-z_][\w$]*)\s*;")


def tile_wires(netlist: Path) -> list[tuple[str, int]]:
    """Return (name, width) for every wire in a tile netlist.

    Escaped identifiers keep a trailing space (required before the next token).
    Vectors are returned whole: iverilog's $deposit cannot target a bit select,
    so vectors are fixed with a read-modify-write of the whole net.
    """
    out: list[tuple[str, int]] = []
    for line in netlist.read_text().splitlines():
        m = WIRE_RE.match(line)
        if not m:
            continue
        name = m.group(4)
        if name.startswith("\\"):
            name += " "
        width = abs(int(m.group(2)) - int(m.group(3))) + 1 if m.group(1) else 1
        out.append((name, width))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--efpga", required=True, type=Path)
    ap.add_argument("--tile-dir", required=True, type=Path)
    ap.add_argument("--top-inst", required=True)
    ap.add_argument("--trigger", required=True)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()

    netlists = {
        nl.parents[3].name: nl
        for nl in sorted(a.tile_dir.glob("*/macro/final_views/nl/*.nl.v"))
    }
    inst_re = re.compile(
        r"^\s*({})\s+(\S+)\s*\(".format("|".join(map(re.escape, netlists)))
    )
    instances = [
        m.groups() for line in a.efpga.read_text().splitlines()
        if (m := inst_re.match(line))
    ]
    wires = {t: tile_wires(p) for t, p in netlists.items()}

    lines = [
        "// AUTO-GENERATED by sim/gl_xscrub_tiles.py -- do not edit by hand.",
        "// Tile-internal X-scrub (complements FABulous force_block.vh).",
        "reg [1023:0] gl_xs_tmp;",
        "integer gl_xs_k;",
        "initial begin : gl_xscrub_tiles",
        f"    wait ({a.trigger} === 1'b1);",
        "    #1;",
    ]
    n = 0
    for ttype, inst in instances:
        for w, width in wires[ttype]:
            ref = f"{a.top_inst}.{inst}.{w}"
            if width == 1:
                lines.append(f"    if ({ref} === 1'bx) $deposit({ref}, 1'b0);")
            else:
                assert width <= 1024, f"{ttype}.{w}: {width} bits > scrub buffer"
                lines.append(
                    f"    if ((^{ref}) === 1'bx) begin gl_xs_tmp = {ref}; "
                    f"for (gl_xs_k = 0; gl_xs_k < {width}; gl_xs_k = gl_xs_k + 1) "
                    f"if (gl_xs_tmp[gl_xs_k] !== 1'b0 && gl_xs_tmp[gl_xs_k] !== 1'b1) "
                    f"gl_xs_tmp[gl_xs_k] = 1'b0; $deposit({ref}, gl_xs_tmp[{width - 1}:0]); end"
                )
            n += width
    lines += [
        f'    $display("gl_xscrub_tiles: checked {n} tile-internal wire bits '
        f'in {len(instances)} tile instances");',
        "end",
    ]
    a.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {a.out}: {n} wire bits, {len(instances)} tile instances")


if __name__ == "__main__":
    main()
